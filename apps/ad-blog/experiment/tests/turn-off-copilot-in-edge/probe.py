    off = pg.evaluate("() => ({x: window.screenX + (window.outerWidth-window.innerWidth), y: window.screenY + (window.outerHeight-window.innerHeight)})")
    box = pg.locator("#para").bounding_box()
    sx, sy = int(off["x"] + box["x"] + 120), int(off["y"] + box["y"] + 15)
    shot(f"{TAG}-1-toolbar")
    xdo("mousemove", str(sx), str(sy)); time.sleep(0.4); xdo("click", "3"); time.sleep(2)
    shot(f"{TAG}-2-rightclick")
    xdo("key", "Escape"); time.sleep(1)
    xdo("mousemove", str(int(off["x"] + box["x"] + 2)), str(sy)); xdo("mousedown", "1")
    xdo("mousemove", str(int(off["x"] + box["x"] + 400)), str(sy)); time.sleep(0.3); xdo("mouseup", "1"); time.sleep(2)
    shot(f"{TAG}-3-minimenu")
    xdo("mousemove", "1100", "700"); xdo("click", "1"); time.sleep(1)
    tb = pg.locator("#note").bounding_box()
    tx, ty = int(off["x"] + tb["x"] + 40), int(off["y"] + tb["y"] + 20)
    xdo("mousemove", str(tx), str(ty)); xdo("click", "1"); time.sleep(1)
    xdo("type", "--delay", "40", "the trail was muddy so we turned back early"); time.sleep(2)
    xdo("key", "ctrl+a"); time.sleep(1)
    xdo("click", "3"); time.sleep(2)
    shot(f"{TAG}-4-textarea-rightclick")
    xdo("key", "Escape"); time.sleep(1)
    xdo("mousemove", str(tx + 300), str(ty)); xdo("click", "1"); time.sleep(1)
    xdo("key", "alt+i"); time.sleep(3)
    shot(f"{TAG}-5-alt-i")
    xdo("key", "Escape"); time.sleep(1)
    xdo("mousemove", "1100", "750"); xdo("click", "1"); time.sleep(1)
    xdo("key", "ctrl+shift+period"); time.sleep(5)
    shot(f"{TAG}-6-shortcut")
